// Copies the poster's textbook phase diagram (the <svg> inside #paper in poster/poster.html) verbatim
// into src/generated/diagram.ts, and checks the copy against the poster. Geometry is never redrawn.
// Run: node docs/classroom/submission/video/scripts/extract-diagram.js [--check]
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const poster = fs.readFileSync(path.join(__dirname, '../../poster/poster.html'), 'utf8');
const start = poster.indexOf('<svg', poster.indexOf('<div id="paper">'));
const end = poster.indexOf('</svg>', start) + '</svg>'.length;
const svg = poster.slice(start, end);
const sha = crypto.createHash('sha256').update(svg).digest('hex');
const out = path.join(__dirname, '../src/generated/diagram.ts');
const body = `// GENERATED by scripts/extract-diagram.js from poster/poster.html (#paper svg). Do not edit.\n` +
  `export const DIAGRAM_SHA256 = ${JSON.stringify(sha)};\nexport const DIAGRAM_SVG = ${JSON.stringify(svg)};\n`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== body) { console.error('diagram.ts differs from poster.html'); process.exit(1); }
  console.log('diagram matches poster, sha256', sha);
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, body);
  console.log('wrote', out, svg.length, 'chars, sha256', sha);
}
