"""Web texture preprocessing and the lunaris-data CLI.

The color map used here is a SYNTHETIC gradient generated by the test, not lunar imagery.
"""

from __future__ import annotations

import io
import json
from pathlib import Path

import httpx
import numpy as np
import pytest
import rasterio

from lunaris_data.cli import EXIT_FAILED, EXIT_OK, EXIT_USAGE, main
from lunaris_data.ingestion import acquire_dataset
from lunaris_data.preprocessing import PreprocessingError, build_web_texture
from lunaris_data.registry import DatasetRegistry
from lunaris_data.store import DataLayout
from tests.data.helpers import FileServer, ManifestFactory, sha256


def _synthetic_rgb_tiff(path: Path, width: int, height: int) -> bytes:
    rows = np.linspace(0, 255, height, dtype=np.uint8)[:, None].repeat(width, axis=1)
    cols = np.linspace(0, 255, width, dtype=np.uint8)[None, :].repeat(height, axis=0)
    with rasterio.open(
        path, "w", driver="GTiff", width=width, height=height, count=3, dtype="uint8"
    ) as dst:
        dst.write(np.stack([rows, cols, np.full_like(rows, 128)]))
    return path.read_bytes()


def _acquired_visual(
    tmp_path: Path,
    file_server: FileServer,
    make_manifest: ManifestFactory,
    layout: DataLayout,
    http_client: httpx.Client,
    *,
    width: int,
    height: int,
) -> tuple[DatasetRegistry, bytes]:
    payload = _synthetic_rgb_tiff(tmp_path / "synthetic.tif", width, height)
    url = file_server.publish("synthetic_color.tif", payload)
    manifest = make_manifest(
        [{"name": "synthetic_color.tif", "url": url, "role": "visual"}],
        dataset_id="synthetic-visual-map",
        category="visualization",
    )
    acquire_dataset(manifest, layout, client=http_client)
    return DatasetRegistry([manifest]), payload


def test_build_web_texture_writes_jpeg_and_provenance(
    tmp_path: Path,
    file_server: FileServer,
    make_manifest: ManifestFactory,
    layout: DataLayout,
    http_client: httpx.Client,
) -> None:
    registry, payload = _acquired_visual(
        tmp_path, file_server, make_manifest, layout, http_client, width=512, height=256
    )
    out_dir = tmp_path / "textures"
    texture = build_web_texture(
        layout, registry, out_dir, dataset_id="synthetic-visual-map", max_width=256
    )

    assert (texture.width, texture.height) == (256, 128)  # downsampled, aspect preserved
    with rasterio.open(out_dir / texture.file) as jpeg:
        assert jpeg.driver == "JPEG"
        assert (jpeg.width, jpeg.height, jpeg.count) == (256, 128, 3)
    assert not list(out_dir.glob("*.aux.xml"))  # no GDAL sidecar files

    manifest_json = json.loads((out_dir / "manifest.json").read_text())
    assert manifest_json["source"]["dataset_id"] == "synthetic-visual-map"
    assert manifest_json["source"]["sha256"] == sha256(payload)
    assert manifest_json["usage"].startswith("Visualization only")
    assert manifest_json["projection"] == "equirectangular"
    assert manifest_json["assumptions"]


def test_build_web_texture_rejects_non_global_map(
    tmp_path: Path,
    file_server: FileServer,
    make_manifest: ManifestFactory,
    layout: DataLayout,
    http_client: httpx.Client,
) -> None:
    registry, _ = _acquired_visual(
        tmp_path, file_server, make_manifest, layout, http_client, width=300, height=300
    )
    with pytest.raises(PreprocessingError, match="2:1"):
        build_web_texture(layout, registry, tmp_path / "out", dataset_id="synthetic-visual-map")


def test_build_web_texture_requires_acquisition(layout: DataLayout, tmp_path: Path) -> None:
    with pytest.raises(PreprocessingError, match="missing"):
        build_web_texture(layout, DatasetRegistry.load_builtin(), tmp_path / "out")


def test_cli_list_show_and_errors(tmp_path: Path) -> None:
    data_dir = ["--data-dir", str(tmp_path / "data")]
    out = io.StringIO()
    assert main([*data_dir, "list"], out=out) == EXIT_OK
    listing = out.getvalue()
    for dataset_id in DatasetRegistry.load_builtin().ids():
        assert dataset_id in listing
    assert "missing" in listing

    out = io.StringIO()
    assert main([*data_dir, "show", "lola-ldem-75s-240m"], out=out) == EXIT_OK
    assert json.loads(out.getvalue())["id"] == "lola-ldem-75s-240m"

    assert main([*data_dir, "show", "no-such-dataset"], out=io.StringIO()) == EXIT_USAGE
    assert main([*data_dir, "verify", "lola-ldem-75s-240m"], out=io.StringIO()) == EXIT_FAILED
