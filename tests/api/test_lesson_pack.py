"""K-02: the committed lesson pack (contract L2) against its manifest and response models.

The pack in ``apps/web/public/lesson-pack/v1/`` is generated by
``scripts/build_lesson_pack.py``. Each file must be byte-for-byte what the manifest
records and must validate against the API response model of the endpoint it stands for,
so the web's existing response types work on it unchanged.
"""

from __future__ import annotations

import hashlib
import json
from datetime import datetime
from pathlib import Path
from typing import Any

import pytest
from pydantic import BaseModel

from lunaris_api.schemas.compare import SiteComparison
from lunaris_api.schemas.ephemeris import MoonPhaseSeries, SunDirectionSeries
from lunaris_api.schemas.horizon import HorizonMaskResponse
from lunaris_api.schemas.illumination import TimelineAnalysis
from lunaris_api.schemas.sites import CandidateSite

PACK = Path(__file__).resolve().parents[2] / "apps/web/public/lesson-pack/v1"
BUDGET_BYTES = 3_000_000
MODELS: dict[str, type[BaseModel]] = {
    "SunDirectionSeries": SunDirectionSeries,
    "MoonPhaseSeries": MoonPhaseSeries,
    "CandidateSite": CandidateSite,
    "HorizonMaskResponse": HorizonMaskResponse,
    "TimelineAnalysis": TimelineAnalysis,
    "SiteComparison": SiteComparison,
}
DEMO_TRIO = {"pgda78-site01", "pgda78-site07", "pgda78-site23"}
VARIANTS = {
    "default": {},
    "power-critical": {"power": "high", "comms": "none", "landing": "none"},
    "comms-critical": {"power": "none", "comms": "high", "landing": "none"},
    "landing-critical": {"power": "none", "comms": "none", "landing": "high"},
}


@pytest.fixture(scope="module")
def manifest() -> dict[str, Any]:
    payload: dict[str, Any] = json.loads((PACK / "manifest.json").read_text(encoding="utf-8"))
    return payload


def test_every_file_matches_its_hash_and_size(manifest: dict[str, Any]) -> None:
    listed = {f["path"] for f in manifest["files"]}
    on_disk = {
        p.relative_to(PACK).as_posix() for p in PACK.rglob("*.json") if p.name != "manifest.json"
    }
    assert listed == on_disk
    for entry in manifest["files"]:
        body = (PACK / entry["path"]).read_bytes()
        assert len(body) == entry["bytes"], entry["path"]
        assert hashlib.sha256(body).hexdigest() == entry["sha256"], entry["path"]
    assert manifest["total_bytes"] == sum(f["bytes"] for f in manifest["files"])


@pytest.mark.parametrize("model_name", sorted(MODELS))
def test_every_file_validates_against_its_response_model(
    manifest: dict[str, Any], model_name: str
) -> None:
    entries = [f for f in manifest["files"] if f["model"] == model_name]
    assert entries, f"no pack file uses {model_name}"
    for entry in entries:
        MODELS[model_name].model_validate_json((PACK / entry["path"]).read_bytes())


def test_pack_is_within_budget(manifest: dict[str, Any]) -> None:
    total = sum(p.stat().st_size for p in PACK.rglob("*") if p.is_file())
    assert total < BUDGET_BYTES, total


def test_series_cover_the_named_lunation_hourly(manifest: dict[str, Any]) -> None:
    lunation = manifest["lunation"]
    window = lunation["window"]
    start = datetime.fromisoformat(window["start_utc"])
    end = datetime.fromisoformat(window["end_utc"])
    assert start <= datetime.fromisoformat(lunation["new_moon_utc"])
    assert end >= datetime.fromisoformat(lunation["next_new_moon_utc"])
    assert window["step_s"] == 3600.0
    phases = [p["phase"] for p in lunation["principal_phases"]]
    assert phases == ["new_moon", "first_quarter", "full_moon", "last_quarter", "new_moon"]
    expected = int((end - start).total_seconds() // 3600) + 1
    for path in ("ephemeris/sun.json", "ephemeris/moon-phase.json"):
        body = json.loads((PACK / path).read_bytes())
        assert body["sample_count"] == len(body["samples"]) == expected
        assert datetime.fromisoformat(body["start_utc"]) == start
        assert datetime.fromisoformat(body["end_utc"]) == end
    moon = json.loads((PACK / "ephemeris/moon-phase.json").read_bytes())
    fractions = [s["illuminated_fraction"] for s in moon["samples"]]
    assert min(fractions) < 0.001
    assert max(fractions) > 0.999


def test_demo_trio_files_and_comparison_variants(manifest: dict[str, Any]) -> None:
    trio = {s["catalog_site_id"]: s for s in manifest["demo_trio"]}
    assert set(trio) == DEMO_TRIO
    site_ids = {s["site_id"] for s in trio.values()}
    for site in trio.values():
        timeline = json.loads(
            (PACK / f"sites/{site['catalog_site_id']}/timeline.json").read_bytes()
        )
        assert timeline["site_id"] == site["site_id"]
        assert timeline["terrain_horizon_available"] is True
    variants = {c["variant"]: c for c in manifest["comparisons"]}
    assert set(variants) == set(VARIANTS)
    for name, answers in VARIANTS.items():
        assert variants[name]["mission_answers"] == answers
        entry = next(f for f in manifest["files"] if f["path"] == variants[name]["file"])
        query = entry["request"]["query"]
        assert {k: v for k, v in query.items() if k != "site_ids"} == answers
        body = json.loads((PACK / entry["path"]).read_bytes())
        assert {row["site_id"] for row in body["rows"]} == site_ids
        assert body["summary"]["recommendation"]["evidence"]["kind"] == "assumption"


def test_manifest_records_provenance(manifest: dict[str, Any]) -> None:
    assert manifest["pack_version"] == "1"
    assert len(manifest["code"]["commit"]) == 40
    ids = {s["source_id"] for s in manifest["sources"]}
    assert "naif-generic-kernels-lunar/de440s.bsp" in ids
    assert "lola-ldem-75s-240m/LDEM_75S_240M.IMG" in ids
    for source in manifest["sources"]:
        if source["source_id"].startswith("constant:"):
            continue  # a cited constant, not a dataset
        # Downloaded datasets carry a SHA-256. The PGDA 20 m DEM is read by HTTP range
        # requests and never downloaded whole, so it is identified by URL plus ETag.
        assert source["sha256"] or (source["url"] and source["version"]), source
    scan = manifest["shadowed_scan"]
    assert scan["ran"] is True
    shadowed = [s for s in scan["sites"] if s["sunlit_fraction"] == 0.0]
    if manifest["permanently_shadowed_example"] is None:
        assert shadowed == []
    else:
        assert manifest["permanently_shadowed_example"]["catalog_site_id"] in {
            s["catalog_site_id"] for s in shadowed
        }
