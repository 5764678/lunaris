"use client";

import { TriangleAlert } from "lucide-react";

import { useT } from "@/lib/i18n";
import type { Evidence, PackProvenance } from "@/lib/lesson/types";

/** Where the numbers came from. A synthetic source is impossible to miss. */
export function PackBanner({ provenance }: { provenance: PackProvenance }) {
  const t = useT().learn.pack;
  if (provenance.kind === "synthetic") {
    return (
      <div
        role="note"
        data-testid="synthetic-banner"
        className="flex items-start gap-2.5 rounded-md border border-ev-placeholder bg-panel p-3 text-sm leading-relaxed text-foreground"
      >
        <TriangleAlert className="mt-0.5 size-4 shrink-0 text-ev-placeholder" aria-hidden="true" />
        <p>
          <strong className="font-semibold text-ev-placeholder">{t.syntheticLabel}.</strong>{" "}
          {t.syntheticDetail}
        </p>
      </div>
    );
  }
  return (
    <p data-testid="pack-label" className="text-sm leading-relaxed text-muted-foreground">
      <strong className="font-medium text-foreground">{t.realLabel(provenance.version)}.</strong>{" "}
      {t.realDetail}
    </p>
  );
}

export const KIND_COLOUR: Record<Evidence["kind"], string> = {
  observation: "text-ev-observation",
  derived_product: "text-ev-derived",
  model: "text-ev-model",
  calculation: "text-ev-calculation",
  assumption: "text-ev-assumption",
  placeholder: "text-ev-placeholder",
};

/**
 * The one evidence label that matters for the step, with the rest folded away. The method
 * and limitation text is generated by the science core and stays English (decision D11).
 */
export function EvidenceFold({
  evidence,
  limitations,
  title,
  testId = "evidence-fold",
  kindTestId = "evidence-kind",
  kindLabel,
}: {
  evidence: Evidence;
  limitations: string[];
  /** Replaces the default heading, which is for the period 2 value. */
  title?: string;
  testId?: string;
  kindTestId?: string;
  /** Shown instead of the raw kind code. */
  kindLabel?: string;
}) {
  const t = useT().learn.earth;
  const c = useT().learn.compare;
  return (
    <details data-testid={testId} className="rounded-md border border-border bg-panel p-3 text-sm">
      <summary className="cursor-pointer font-medium text-foreground">
        {title ?? t.evidenceHeading}:{" "}
        <span data-testid={kindTestId} className={KIND_COLOUR[evidence.kind]}>
          {kindLabel ?? evidence.kind}
        </span>
      </summary>
      <div className="mt-2 space-y-2 leading-relaxed text-muted-foreground">
        <p className="text-dim">{t.evidenceEnglishNote}</p>
        <p lang="en">{evidence.statement}</p>
        {evidence.method && (
          <p lang="en">
            <strong className="font-medium text-foreground">{t.method}:</strong> {evidence.method}
          </p>
        )}
        {evidence.sources.length > 0 && (
          <div>
            <p className="font-medium text-foreground">{c.sources}</p>
            <ul lang="en" className="list-disc space-y-1 pl-5">
              {evidence.sources.map((source) => (
                <li key={source.source_id}>{source.title}</li>
              ))}
            </ul>
          </div>
        )}
        {limitations.length > 0 && (
          <div>
            <p className="font-medium text-foreground">{t.limitations}</p>
            <ul lang="en" className="list-disc space-y-1 pl-5">
              {limitations.map((line) => (
                <li key={line}>{line}</li>
              ))}
            </ul>
          </div>
        )}
      </div>
    </details>
  );
}
