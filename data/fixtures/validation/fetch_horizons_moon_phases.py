"""Fetch the JPL Horizons validation fixture for the Moon phase series (K-01, L1).

Writes ``horizons-moon-phases-2027.json`` next to this file:

* ``longitudes``: apparent geocentric ecliptic longitude **of date** (``QUANTITIES='31'``)
  of the Moon (301) and the Sun (10), every minute from 5 min before to 6 min after each
  2027 principal phase instant given on the command line (a JSON list of
  ``[phase, iso_utc]``). Horizons truncates ``TLIST`` silently at 80 epochs, so the
  epochs are sent in batches of four events (48 epochs). The test finds Horizons' own
  instant as the zero of ``λ☾ − λ☉ − target`` in these rows.
* ``samples``: geocentric illuminated fraction, sub-observer point, S-O-T elongation and
  S-T-O phase angle (``QUANTITIES='10,14,23,24'``) every 6 h over January 2027.

Every request is stored with its exact parameters and the verbatim ``$$SOE…$$EOE`` block.
Run: ``uv run python data/fixtures/validation/fetch_horizons_moon_phases.py ours.json``.
"""

from __future__ import annotations

import json
import sys
import time
import urllib.parse
import urllib.request
from datetime import UTC, datetime, timedelta
from pathlib import Path

API = "https://ssd.jpl.nasa.gov/api/horizons.api"
OUT = Path(__file__).with_name("horizons-moon-phases-2027.json")
EVENTS_PER_BATCH = 4
JD_UNIX_EPOCH = 2440587.5


def _jd(t: datetime) -> float:
    return JD_UNIX_EPOCH + (t - datetime(1970, 1, 1, tzinfo=UTC)).total_seconds() / 86400.0


def _request(params: dict[str, str]) -> str:
    data = urllib.parse.urlencode(params).encode()
    with urllib.request.urlopen(urllib.request.Request(API, data=data), timeout=300) as r:
        text: str = r.read().decode()
    start, end = text.index("$$SOE"), text.index("$$EOE") + len("$$EOE")
    time.sleep(1.0)
    return text[start:end]


def _common(body: str) -> dict[str, str]:
    return {
        "format": "text",
        "COMMAND": f"'{body}'",
        "OBJ_DATA": "'NO'",
        "MAKE_EPHEM": "'YES'",
        "EPHEM_TYPE": "'OBSERVER'",
        "CENTER": "'500@399'",
        "EXTRA_PREC": "'YES'",
        "CSV_FORMAT": "'YES'",
    }


def main(events_path: str) -> None:
    events = json.loads(Path(events_path).read_text(encoding="utf-8"))
    batches = []
    for b in range(0, len(events), EVENTS_PER_BATCH):
        chunk = events[b : b + EVENTS_PER_BATCH]
        epochs = []
        for _, iso in chunk:
            t = datetime.fromisoformat(iso).replace(tzinfo=UTC, second=0, microsecond=0)
            epochs += [t + timedelta(minutes=k) for k in range(-5, 7)]
        tlist = " ".join(f"'{_jd(t):.10f}'" for t in epochs)
        batch: dict[str, object] = {"events": [phase for phase, _ in chunk]}
        for name, body in (("moon", "301"), ("sun", "10")):
            params = _common(body) | {
                "TLIST_TYPE": "'JD'",
                "TIME_TYPE": "'UT'",
                "TLIST": tlist,
                "QUANTITIES": "'31'",
                "TIME_DIGITS": "'SECONDS'",
            }
            batch[name] = {"params": params, "block": _request(params)}
        batches.append(batch)
    sample_params = _common("301") | {
        "START_TIME": "'2027-01-01 00:00'",
        "STOP_TIME": "'2027-02-01 00:00'",
        "STEP_SIZE": "'6 h'",
        "QUANTITIES": "'10,14,23,24'",
        "ANG_FORMAT": "'DEG'",
    }
    payload = {
        "source": "NASA/JPL Horizons API (https://ssd.jpl.nasa.gov/api/horizons.api), DE441",
        "retrieved_utc": datetime.now(UTC).replace(microsecond=0).isoformat(),
        "notes": (
            "QUANTITIES='31' is the apparent observer-centred ecliptic longitude and latitude "
            "of date. Times are UTC. Generated by fetch_horizons_moon_phases.py."
        ),
        "longitudes": batches,
        "samples": {"params": sample_params, "block": _request(sample_params)},
    }
    OUT.write_text(json.dumps(payload, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1])
